/** Only the fields cards need: keeps case-study notes (and TODOs) out of client bundles. */
export type CardData = Pick<Project, "slug" | "title" | "tagline" | "category" | "featured" | "cover"> & { date: string | null };
export const toCard = (p: Project, date: string | null): CardData => ({
  slug: p.slug, title: p.title, tagline: p.tagline, category: p.category, featured: !!p.featured, cover: p.cover, date,
});

export { categories } from "./types";

export const getProject = (slug: string) => projects.find((p) => p.slug === slug);
export const featuredProjects = projects.filter((p) => p.featured);
export const otherProjects = projects.filter((p) => !p.featured);
